#!/usr/bin/env python3
"""Generate inert Dots route headers from bundled application grammars."""
import argparse
import importlib.util
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.dont_write_bytecode = True


def grammars():
    spec = importlib.util.spec_from_file_location('blastoff_grammar', ROOT/'plugins/blastoff/lib/cli.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    yield 'blastoff', module.parser((ROOT/'plugins/blastoff/VERSION').read_text().strip()), None
    sys.path.insert(0, str(ROOT/'plugins/pkgs'))
    from pkgs_lib.grammar import parser, COMMANDS
    yield 'pkgs', parser(), COMMANDS


def clean(value):
    return ' '.join(str(value or '').replace('|', '/').split())


def options(parser):
    rows = []
    for action in parser._actions:
        long = next((s for s in action.option_strings if s.startswith('--')), None)
        if not long:
            continue
        short = next((s for s in action.option_strings if not s.startswith('--')), '')
        kind = ('flag' if action.nargs == 0 else 'choice:'+','.join(map(str, action.choices))
                if action.choices else 'directory' if action.dest == 'directory' else 'file' if action.dest == 'output' else 'string')
        rows.append([long, short, kind, clean(action.help or action.dest.replace('_', ' '))])
    return rows


def records():
    for name, parser, commands in grammars():
        common = options(parser)
        def walk(current, route):
            inherited = [r for r in common if r[0] != '--version' or len(route) == 1]
            opts = {r[0]: r for r in [*inherited, *options(current)]}
            args = []
            summary = clean(current.description or 'Manage '+route[-1]).split('. ')[0]
            children = []
            for action in current._actions:
                if isinstance(action, argparse._SubParsersAction):
                    children.extend(action.choices.items())
                elif not action.option_strings and action.dest not in ('command', 'names'):
                    kind = ('choice:'+','.join(map(str, action.choices)) if action.choices else
                            'directory' if action.dest == 'path' and route[-1] == 'migrate' else
                            'file' if action.dest == 'path' else 'string')
                    args.append([str(len(args)+1), kind, clean(action.help or action.dest)])
            yield '-'.join(route), dict(summary=summary, option=list(opts.values()), argument=args)
            for child, grammar in children:
                yield from walk(grammar, [*route, child])
        if commands:
            yield name, dict(summary='Manage packages on Termux, Linux and WSL', option=common, argument=[])
            for command, summary in commands.items():
                args = [['1', 'choice:bash,zsh,fish', 'Shell'], ['2', 'choice:install,update,status,uninstall', 'Completion action']] if command == 'completion' else [['1', 'choice:clear', 'Cache action']] if command == 'cache' else [['1','file','Package manifest']] if command in ('manifest','restore') else []
                yield name+'-'+command, dict(summary=summary, option=common, argument=args)
        else:
            yield from walk(parser, [name])


def outputs():
    rows = dict(records())
    for stem, row in rows.items():
        family, *route = stem.split('-')
        lines = ['#!/usr/bin/env bash', '# Generated by tools/generate_bundled_apps.py.']
        lines += ['# dots:summary='+row['summary'], '# dots:usage=[OPTIONS] [ARGUMENTS]']
        for key in ('option', 'argument'):
            lines += ['# dots:'+key+'='+'|'.join(record) for record in row[key]]
        # These route tokens come exclusively from the fixed parser grammar.
        lines += ['exec "${BASH_SOURCE[0]%/*}/'+family+'"'+(' '+' '.join(route) if route else '')+' "$@"']
        yield ROOT/'bin'/('dots-'+stem), '\n'.join(lines)+'\n'
    yield ROOT/'lib/dots/metadata/bundled-apps.json', json.dumps(rows, indent=2)+'\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, text in outputs():
        if args.check:
            if not path.is_file() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text)
            if path.parent.name == 'bin': path.chmod(0o755)
    if stale:
        sys.exit('Stale bundled metadata: '+', '.join(stale))


if __name__ == '__main__':
    main()
