#!/usr/bin/env python3
"""Generate the complete first-party dots(1); --check performs no writes."""
import argparse
from pathlib import Path
import sys
import textwrap

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'lib/dots'))
from wiki import Reader
from wiki_commands import global_options, inventory


def roff(text):
    text = str(text).replace('\\', r'\e').replace('-', r'\-').replace('"', r'\(dq')
    return '\n'.join((r'\&' if line.startswith(('.', "'")) else '') + line
                     for line in text.split('\n'))


def manual(root=ROOT):
    reader = Reader(root)
    lines = [r'.\" Generated by tools/generate_dots_manual.py; do not edit.',
             '.TH DOTS 1 "October 31, 2026" "Dots" "User Commands"', '.SH NAME',
             r'dots \- manage dotfiles, shells, themes and checkout workflows',
             '.SH SYNOPSIS', '.B dots', '[GLOBAL OPTIONS] COMMAND [ARGUMENTS]',
             '.SH DESCRIPTION',
             'Dots provides shared command families on Termux, Linux, WSL and native Windows.',
             'On native Windows use dots.ps1. Public first-party routes below come from',
             'static metadata; optional and private extensions are not included or executed.',
             'Platform limitations belong to each command and its linked guide.',
             '.SH GLOBAL OPTIONS', 'These options precede the command.']
    for long, short, kind, description in global_options(reader):
        label = long + (', ' + short if short else '')
        if kind != 'flag':
            label += ' ' + (kind[7:] if kind.startswith('choice:') else 'VALUE')
        lines += ['.TP', '.B "' + roff(label) + '"', roff(description)]
    lines += ['.SH COMMANDS']
    for row in inventory(reader):
        lines += ['.SS "' + roff(row['route']) + '"', roff(row['summary']),
                  '.PP', '.B "' + roff((row['route'] + ' ' + row['usage']).rstrip()) + '"']
        for long, short, kind, description in row['option']:
            label = long + (', ' + short if short else '')
            if kind != 'flag':
                label += ' ' + (kind[7:] if kind.startswith('choice:') else 'VALUE')
            lines += ['.TP', '.B "' + roff(label) + '"', roff(description)]
        for position, kind, description in row['argument']:
            lines += ['.TP', '.B "Argument ' + roff(position) + ' (' + roff(kind) + ')"', roff(description)]
        for example in row['example']:
            lines += ['.PP', '.nf', roff(example), '.fi']
    lines += ['.SH EXAMPLES', '.nf',
              'dots help files', 'dots menu', 'dots files install --dry-run',
              'dots wiki search "config precedence" --topics', 'dots config explain apps.menu.popup.width',
              '.fi', '.SH ENVIRONMENT',
              '.TP', '.B DOTS', 'Select the checkout used by command adapters.',
              '.TP', '.B DOTS_COLOR, DOTS_ICONS, NO_COLOR',
              'Control human presentation. Structured output and completion remain undecorated.',
              '.TP', '.B DOTS_PROGRESS', 'Set to never to disable operation progress.',
              '.TP', '.B DOTS_WIKI_DIR', 'Override the separate generated wiki checkout location.',
              '.TP', '.B XDG_CONFIG_HOME, XDG_STATE_HOME, XDG_DATA_HOME',
              'Override supported POSIX configuration, state and data roots. Native Windows',
              'uses its own platform destinations; see the Platforms and PowerShell guides.',
              '.SH FILES', '.TP', '.B profiles/ID/profile.json',
              'Profile mappings, settings and application environment declarations.',
              '.TP', '.B default/', 'Shared configuration and theme templates.',
              '.TP', '.B .dots/files.json, .dots/sources.json',
              'Managed resource identities and source repositories.',
              '.TP', '.B .dots/wiki.json', 'Canonical documentation mappings and wiki navigation.',
              '.SH SAFETY',
              'Review the selected command help and supported dry-run before a managed change.',
              'Managed file changes use preflight, journals and retained recovery records.',
              'Undo refuses destructive restoration after drift. Package and external effects',
              'have their own boundaries; filesystem rollback cannot undo every external action.',
              'Documentation lookup does not install, activate or publish anything.',
              '.SH SEE ALSO',
              'https://github.com/5nik7/dots/wiki', '.br',
              'https://github.com/5nik7/dots/wiki/Command-reference', '.br',
              'dots help ROUTE, dots wiki browse, dots wiki search QUERY --topics', '']
    output, literal = [], False
    for line in lines:
        if line == '.nf': literal = True
        if line == '.fi': literal = False
        output.extend([line] if literal or line.startswith('.') else
                      textwrap.wrap(line, width=78, break_long_words=False, break_on_hyphens=False) or [''])
    return '\n'.join(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'man/dots.1'
    content = manual()
    if args.check:
        if not target.is_file() or target.read_text(encoding='utf-8') != content:
            print('dots manual is stale; run python3 -B tools/generate_dots_manual.py', file=sys.stderr)
            return 1
        print('dots manual is current.')
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding='utf-8')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
