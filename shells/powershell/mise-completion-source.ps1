# Return a dot-sourceable provider for either mise installation route.
[CmdletBinding(DefaultParameterSetName='Source')]
param(
  [Parameter(Mandatory, ParameterSetName='Source')][string]$Source,
  [Parameter(Mandatory, ParameterSetName='Path')][string]$Path
)

if ($Path) { $Source = [IO.File]::ReadAllText($Path) }
$header = '# @generated by usage-argv for `mise __complete_word__ --shell powershell`'
if ($Source.StartsWith($header, [StringComparison]::Ordinal)) {
  # CommandAst ends at the last token. Keep the gap when Tab follows a space.
  $newline = if ($Source.Contains("`r`n")) { "`r`n" } else { "`n" }
  $clamp = 'if ($offset -gt $extent.Text.Length) { $offset = $extent.Text.Length }' + $newline +
           '    $line = $extent.Text.Substring(0, $offset)'
  if ($Source.Contains($clamp)) {
    $corrected = '$line = $extent.Text.PadRight($offset).Substring(0, $offset)'
    return [ScriptBlock]::Create($Source.Replace($clamp, $corrected))
  }
}

# Other installed providers retain their file path and normal script scope.
if ($Path) { return $Path }
return [ScriptBlock]::Create($Source)
