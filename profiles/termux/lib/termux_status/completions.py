"""Static completions, adapted from the repository's termux-sessions CLI."""

import os
from pathlib import Path
import shlex
import stat
import sys
import tempfile

from .cli import ALIASES, SHELLS
from .providers import STREAMS


def completion_source(command, fields, options, shell):
    source = _completion_source(fields, options, shell)
    return source.replace("termux-sessions", command).replace("termux_sessions", command.replace("-", "_")).replace("session discovery", "Android API calls")


def _completion_source(FIELDS, OPTIONS, shell):
    kinds = {name: kind or "" for names, _, kind, _ in OPTIONS for name in names}
    kinds.update({alias: kinds[option] for alias, option in ALIASES.items()})
    choices = " ".join(FIELDS)
    root = " ".join(name for names, _, _, group in OPTIONS if group not in ("install",)
                    for name in names) + " " + " ".join(ALIASES)
    if shell == "bash":
        cases = "\n".join(f"    {name}) printf '%s' {shlex.quote(kind)} ;;"
                          for name, kind in kinds.items() if kind)
        return r'''# Generated by termux-sessions; no runtime session discovery.
_termux_sessions_kind() {
  case $1 in
@CASES@
  esac
}
_termux_sessions() {
  local cur=${COMP_WORDS[COMP_CWORD]} word kind='' mode='' lead='' prefix fragment field i
  COMPREPLY=()
  for ((i=1; i<COMP_CWORD; i++)); do
    word=${COMP_WORDS[i]}
    if [[ -n $kind ]]; then
      if [[ $kind != shell || $word != -* ]]; then kind=''; continue; fi
      kind=''
    fi
    case $word in
      get|-g|--get|--get=*) mode=get ;;
      format|-f|--format|--format=*) mode=format ;;
      completion|--completion|--completion=*) mode=completion ;;
    esac
    kind=$(_termux_sessions_kind "${word%%=*}")
    [[ $word == *=* ]] && kind=''
  done
  if [[ $cur == --*=* ]]; then
    kind=$(_termux_sessions_kind "${cur%%=*}")
    lead=${cur%%=*}=
    cur=${cur#*=}
  fi
  [[ $kind == shell && $cur == -* ]] && kind=''
  case $kind in
    field) mapfile -t COMPREPLY < <(compgen -W '@FIELDS@' -- "$cur") ;;
    shell) mapfile -t COMPREPLY < <(compgen -W '@SHELLS@' -- "$cur") ;;
    stream) mapfile -t COMPREPLY < <(compgen -W "@STREAMS@" -- "$cur") ;;
    directory)
      mapfile -t COMPREPLY < <(compgen -d -- "$cur")
      compopt -o filenames 2>/dev/null || : ;;
    template)
      prefix=''; fragment=$cur
      if [[ $cur == *\{* ]]; then prefix=${cur%\{*}; fragment=${cur##*\{}; fi
      for field in @FIELDS@; do
        [[ $field == "$fragment"* ]] && COMPREPLY+=("${prefix}{${field}}")
      done ;;
    cell|package) ;;
    *)
      case $mode in
        completion) word='--install --all --dir -h --help' ;;
        get|format) word='@SELECTORS@ -h --help' ;;
        *) word='@ROOT@' ;;
      esac
      mapfile -t COMPREPLY < <(compgen -W "$word" -- "$cur") ;;
  esac
  if [[ -n $lead ]]; then
    for ((i=0; i<${#COMPREPLY[@]}; i++)); do COMPREPLY[i]=$lead${COMPREPLY[i]}; done
  fi
  return 0
}
complete -F _termux_sessions termux-sessions
'''.replace("@STREAMS@", " ".join(STREAMS)).replace("@CASES@", cases).replace("@FIELDS@", choices).replace(
            "@SHELLS@", " ".join(SHELLS)).replace("@ROOT@", root).replace("@SELECTORS@", " ".join(name for names, _, _, group in OPTIONS if group == "selector" for name in names))
    if shell == "zsh":
        actions = {"field": "(" + choices + ")", "shell": "(" + " ".join(SHELLS) + ")",
                   "stream": "(" + " ".join(STREAMS) + ")", "template": "->template", "directory": "_files -/", "cell": "", "package": ""}
        groups = {}
        for group in ("mode", "selector", "install", "help"):
            specs = []
            for names, description, kind, category in OPTIONS:
                if category != group:
                    continue
                exclusion = ""
                if group == "mode":
                    exclusion = "(" + " ".join(n for ns, _, _, g in OPTIONS if g == group for n in ns) + ")"
                for name in names:
                    value = (":" if kind != "shell" else "::") + kind + ":" + actions[kind] if kind else ""
                    spelling = name + "=" if kind and name.startswith("--") else name
                    if kind == "package":
                        spelling = "*" + spelling
                    specs.append(shlex.quote(exclusion + spelling + "[" + description + "]" + value))
            groups[group] = " ".join(specs)
        return r'''#compdef termux-sessions
# Generated by termux-sessions; no runtime session discovery.
_termux_sessions() {
  local context state state_descr line curcontext="$curcontext" prefix fragment field template_lead=''
  local -a specs candidates
  typeset -A opt_args
  [[ ${words[CURRENT]} == --format=* ]] && template_lead='--format='
  specs=(@SELECTOR@ @HELP@)
  case ${words[2]} in
    get) words=($words[1] $words[3,-1]); (( CURRENT-- )); specs+=('1:field:(@FIELDS@)') ;;
    format) words=($words[1] $words[3,-1]); (( CURRENT-- )); specs+=('1:template:->template') ;;
    completion) words=($words[1] $words[3,-1]); (( CURRENT-- )); specs=(@HELP@ @INSTALL@ '1:shell:(@SHELLS@)') ;;
    *)
      specs+=(@MODE@ '1:command:(get format completion)')
      if (( ${words[(I)--completion*]} )); then specs+=(@INSTALL@); fi ;;
  esac
  _arguments -C $specs && return 0
  if [[ $state == template ]]; then
    fragment=${(Q)PREFIX}; fragment=${fragment#--format=}; prefix=''
    if [[ $fragment == *\{* ]]; then prefix=${fragment%\{*}; fragment=${fragment##*\{}; fi
    for field in @FIELDS@; do
      [[ $field == "$fragment"* ]] && candidates+=("${prefix}{${field}}")
    done
    compadd -Q -U -P "$template_lead" -a candidates
  fi
}
_termux_sessions "$@"
'''.replace("@FIELDS@", choices).replace("@SHELLS@", " ".join(SHELLS)).replace(
            "@SELECTOR@", groups["selector"]).replace("@HELP@", groups["help"]).replace(
            "@MODE@", groups["mode"]).replace("@INSTALL@", groups["install"])
    # Fish conditions parse words without executing termux-sessions. The
    # helper prints a value kind, or a mode after its value has been consumed.
    cases = "\n".join("            case " + shlex.quote(name) + "\n                set pending "
                      + shlex.quote(kind) for name, kind in kinds.items() if kind)
    source = '''# Generated by termux-sessions; no runtime session discovery.
function __termux_sessions_context
    set -l words (commandline -opc)
    set -l pending ''
    set -l mode root
    for word in $words[2..-1]
        if test -n "$pending"
            if test "$pending" != shell; or not string match -q -- '-*' "$word"
                set pending ''
                continue
            end
            set pending ''
        end
        switch $word
            case get -g --get '--get=*'
                set mode get
            case format -f --format '--format=*'
                set mode format
            case completion --completion '--completion=*'
                set mode completion
        end
        switch (string split -m1 = -- "$word")[1]
@CASES@
        end
        if string match -q '*=*' -- "$word"
            set pending ''
        end
    end
    set -l token (commandline -ct)
    if string match -q -- '--*=*' "$token"
        switch (string split -m1 = -- "$token")[1]
@CASES@
        end
    end
    if test "$pending" = shell; and string match -q -- '-*' "$token"
        set pending ''
    end
    if test -n "$pending"
        printf '%s\\n' "$pending"
    else
        printf '%s\\n' "$mode"
    end
end
complete -c termux-sessions -f
complete -c termux-sessions -n 'test (__termux_sessions_context) = root' -a 'get format completion'
complete -c termux-sessions -n 'test (__termux_sessions_context) = field' -a '@FIELDS@'
complete -c termux-sessions -n 'test (__termux_sessions_context) = shell' -a '@SHELLS@'
complete -c termux-sessions -n 'test (__termux_sessions_context) = stream' -a '@STREAMS@'
complete -c termux-sessions -n 'test (__termux_sessions_context) = directory' -a '(__fish_complete_directories)'
'''.replace("@STREAMS@", " ".join(STREAMS)).replace("@CASES@", cases).replace("@FIELDS@", choices).replace("@SHELLS@", " ".join(SHELLS))
    source += r'''function __termux_sessions_templates
    set -l token (commandline -ct)
    set token (string replace -r '^--format=' '' -- "$token")
    set token (string replace -r "^[\"']" '' -- "$token")
    set -l prefix ''
    if string match -q '*{*' -- "$token"
        set prefix (string replace -r '\{[^{]*$' '' -- "$token")
    end
    for field in @FIELDS@
        printf '%s{%s}\n' "$prefix" "$field"
    end
end
complete -c termux-sessions -n 'test (__termux_sessions_context) = template' -a '(__termux_sessions_templates)'
'''.replace("@FIELDS@", choices)
    for names, description, kind, group in OPTIONS:
        condition = {"mode": "contains -- (__termux_sessions_context) root",
                     "selector": "contains -- (__termux_sessions_context) root get format",
                     "install": "contains -- (__termux_sessions_context) completion shell",
                     "help": "contains -- (__termux_sessions_context) root get format completion shell"}[group]
        if group == "mode" and kind:
            condition += " " + kind
        flags = " ".join(("-l " + name[2:]) if name.startswith("--") else ("-s " + name[1:]) for name in names)
        source += "complete -c termux-sessions " + flags + " -n " + shlex.quote(condition)
        source += " -d " + shlex.quote(description)
        if kind:
            if kind != "shell":
                source += " -r"
            if kind in ("field", "shell", "template", "stream"):
                source += " -a " + shlex.quote({"field": choices, "shell": " ".join(SHELLS),
                                                "template": "(__termux_sessions_templates)", "stream": " ".join(STREAMS)}[kind])
        source += "\n"
    return source


def completion_targets(command, shells, directory):
    env = os.environ
    home = Path(env.get("HOME") or str(Path.home()))
    data = Path(env.get("XDG_DATA_HOME") or home / ".local/share")
    config = Path(env.get("XDG_CONFIG_HOME") or home / ".config")
    bash_base = next((Path(p) for p in env.get("BASH_COMPLETION_USER_DIR", "").split(":") if p),
                     data / "bash-completion")
    prefix = env.get("TERMUX__PREFIX") or env.get("PREFIX")
    defaults = {"bash": bash_base / "completions",
                "zsh": Path(prefix) / "share/zsh/site-functions" if prefix else data / "zsh/site-functions",
                "fish": config / "fish/completions"}
    filenames = {"bash": command + ".bash", "zsh": "_" + command, "fish": command + ".fish"}
    return [(shell, (Path(directory).expanduser() if directory else defaults[shell]) / filenames[shell])
            for shell in shells]


def install_completions(command, fields, options, targets):
    pending = []
    # Validate every leaf and its nearest existing parent before any writes.
    for shell, path in targets:
        if path.is_symlink() or (path.exists() and not path.is_file()):
            raise OSError(f"refusing non-regular completion target: {path}")
        parent = path.parent
        while not parent.exists():
            parent = parent.parent
        if not parent.is_dir() or not os.access(parent, os.W_OK):
            raise OSError(f"completion directory is not writable: {parent}")
        content = completion_source(command, fields, options, shell).encode()
        old = path.read_bytes() if path.exists() else None
        pending.append((path, content, old))
    for path, content, old in pending:
        if old == content:
            print(f"unchanged: {path}", file=sys.stderr)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        mode = stat.S_IMODE(path.stat().st_mode) if old is not None else 0o644
        if old is not None:
            with tempfile.NamedTemporaryFile(prefix=path.name + ".bak.", dir=path.parent, delete=False) as backup:
                backup.write(old)
            os.chmod(backup.name, mode)
            print(f"backup: {backup.name}", file=sys.stderr)
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(prefix="." + path.name + ".", dir=path.parent, delete=False) as stream:
                temporary = Path(stream.name)
                stream.write(content)
            temporary.chmod(mode)
            os.replace(temporary, path)
        finally:
            if temporary is not None:
                temporary.unlink(missing_ok=True)
        print(f"installed: {path}", file=sys.stderr)

