"""Static contextual completion; explicit installation uses shared transactions."""
from pathlib import Path
from core import ROOT, FIELDS
from metadata import OPTIONS, BROWSE_OPTIONS, SHELLS, STOCK_WORDS, STOCK_DESCRIPTIONS, SHORT_FLAGS, spellings

FILES = dict(bash='wttr.bash', zsh='_wttr', fish='wttr.fish', powershell='wttr.ps1')


def choices():
    return {name: (list(FIELDS) if flag == '--get' else value.split('|') if value and '|' in value else [])
            for flag, value, _ in [*OPTIONS, *BROWSE_OPTIONS] if value for name in spellings(flag)}


def generate(shell):
    options = ' '.join(name for flag, _, _ in OPTIONS for name in spellings(flag))
    browse_options = ' '.join(name for flag, _, _ in BROWSE_OPTIONS for name in spellings(flag))
    stock_words = ' '.join(STOCK_WORDS)
    values = choices()
    file_flags = (*spellings('--config'), '--dir')
    help_flags = spellings('--help')
    if shell == 'bash':
        cases = '\n'.join(f"    {flag}) COMPREPLY=( $(compgen -W '{' '.join(items)}' -- \"$cur\") ); return ;;" for flag, items in values.items() if items)
        return '''# Generated by wttr completion bash; no weather calls.
_wttr() {
  local cur=${COMP_WORDS[COMP_CWORD]} prev=${COMP_WORDS[COMP_CWORD-1]}
  COMPREPLY=()
  # Readline splits :translation at ':' with its default word breaks.
  if [[ $prev == : ]]; then
    case "${COMP_WORDS[COMP_CWORD-2]}" in
      VALUE_FLAGS|--dir|get) return ;;
    esac
    COMPREPLY=( $(compgen -W 'PAGES' -- "$cur") )
    return
  fi
  case "$prev" in
'''.replace('PAGES', ' '.join(w[1:] for w in STOCK_WORDS if w.startswith(':'))).replace('VALUE_FLAGS', '|'.join(values)) + cases + '''
    get) COMPREPLY=( $(compgen -W 'FIELDS' -- "$cur") ); return ;;
    FILE_FLAGS) compopt -o filenames 2>/dev/null; mapfile -t COMPREPLY < <(compgen -f -- "$cur"); return ;;
    VALUE_FLAGS) return ;;
  esac
  if [[ ${COMP_WORDS[1]} == completion ]]; then
    COMPREPLY=( $(compgen -W 'bash zsh fish powershell --all --install --dir HELP_FLAGS' -- "$cur") )
  elif [[ ${COMP_WORDS[1]} == browse ]]; then
    COMPREPLY=( $(compgen -W 'BROWSE_OPTIONS' -- "$cur") )
  else
    COMPREPLY=( $(compgen -W 'OPTIONS get completion browse STOCK' -- "$cur") )
  fi
  if [[ $cur == :* && $COMP_WORDBREAKS == *:* ]]; then
    COMPREPLY=( "${COMPREPLY[@]#:}" )
  fi
}
complete -F _wttr wttr
'''.replace('FIELDS', ' '.join(FIELDS)).replace('BROWSE_OPTIONS', browse_options).replace('OPTIONS', options).replace('STOCK', stock_words).replace('FILE_FLAGS', '|'.join(file_flags)).replace('VALUE_FLAGS', '|'.join(values)).replace('HELP_FLAGS', ' '.join(help_flags))
    if shell == 'zsh':
        descriptions = {**STOCK_DESCRIPTIONS, 'get': 'Query a weather field', 'completion': 'Generate or install completions', 'browse': 'Browse weather and session controls'}
        described = ' '.join("'" + word.replace(':', '\\:') + ':' + description.replace(':', '\\:') + "'" for word, description in descriptions.items())
        specs, browse_specs = [], []
        for flag, value, description in [*OPTIONS, *[row for row in BROWSE_OPTIONS if row not in OPTIONS]]:
            action = ''
            if value:
                action = ':value:' + ('(' + ' '.join(values[flag]) + ')' if values[flag] else '_files' if flag == '--config' else '')
            names = spellings(flag)
            exclusion = '(' + ' '.join(names) + ')' if len(names) > 1 else ''
            for name in names:
                spec = "  '" + exclusion + name + '[' + description.replace("'", '') + ']' + action + "'"
                if (flag, value, description) in OPTIONS: specs.append(spec)
                if (flag, value, description) in BROWSE_OPTIONS: browse_specs.append(spec)
        return '#compdef wttr\n# Generated by wttr; no weather calls.\n_wttr() {\n  local context state state_descr line\n  typeset -A opt_args\n' + '''  if [[ $words[2] == completion ]]; then
    _arguments '--all[All shells]' '--install[Install with backup]' '--dir[Destination]:directory:_files -/' HELP_FLAGS '*:shell:(bash zsh fish powershell)'
  elif [[ $words[2] == browse ]]; then
    _arguments -s BROWSE_SPECS '*:location:'
  else
    _arguments -s \\
'''.replace('BROWSE_SPECS', ' '.join(browse_specs)).replace('HELP_FLAGS', ' '.join("'(" + ' '.join(help_flags) + ')' + flag + "[Show help]'" for flag in help_flags)) + ' \\\n'.join(specs) + " \\\n  '*:argument:->argument'\n    if [[ $state == argument ]]; then\n      if [[ $words[2] == get ]]; then\n        compadd -- FIELDS\n      else\n        local -a stock_options\n        stock_options=(DESCRIBED)\n        _describe -t wttr-stock-options 'wttr.in options' stock_options\n      fi\n    fi\n  fi\n}\n_wttr \"$@\"\n".replace('FIELDS', ' '.join(FIELDS)).replace('STOCK', stock_words).replace('DESCRIBED', described)
    if shell == 'fish':
        rows = ['# Generated by wttr; no weather calls.', 'complete -c wttr -f',
                "complete -c wttr -n '__fish_use_subcommand' -a 'get completion browse'",
                "complete -c wttr -n '__fish_prev_arg_in get' -a '" + ' '.join(FIELDS) + "'",
                "complete -c wttr -n '__fish_seen_subcommand_from completion' -a 'bash zsh fish powershell'",
                "complete -c wttr -n '__fish_seen_subcommand_from completion' -l all -d 'All shells'",
                "complete -c wttr -n '__fish_seen_subcommand_from completion' -l install -d 'Install with backup'",
                "complete -c wttr -n '__fish_seen_subcommand_from completion' -l dir -r -F -d 'Destination directory'",
                "complete -c wttr -n '__fish_seen_subcommand_from completion' -l help -s " + SHORT_FLAGS['--help'][1:] + " -d 'Show help'"]
        for word, description in STOCK_DESCRIPTIONS.items():
            rows.append("complete -c wttr -n 'not __fish_seen_subcommand_from get completion browse; and not __fish_prev_arg_in " + " ".join(values) + "' -a '" + word + "' -d '" + description + "'")
        for flag, value, description in [*OPTIONS, *[row for row in BROWSE_OPTIONS if row not in OPTIONS]]:
            condition = ('not __fish_seen_subcommand_from completion' if (flag, value, description) in BROWSE_OPTIONS and (flag, value, description) in OPTIONS else
                         '__fish_seen_subcommand_from browse' if (flag, value, description) in BROWSE_OPTIONS else
                         'not __fish_seen_subcommand_from completion browse')
            row = f"complete -c wttr -n '{condition}' -l {flag[2:]} -d '{description}'"
            if flag in SHORT_FLAGS:
                row += ' -s ' + SHORT_FLAGS[flag][1:]
            if value:
                row += ' -r'
                if flag == '--config': row += ' -F'
                if values[flag]: row += " -a '" + ' '.join(values[flag]) + "'"
            rows.append(row)
        return '\n'.join(rows) + '\n'
    if shell == 'powershell':
        descriptions = {**STOCK_DESCRIPTIONS, **{name: desc for flag, _, desc in [*OPTIONS, *BROWSE_OPTIONS] for name in spellings(flag)}}
        tooltips = "\n".join("    $descriptions.Add('" + word.replace("'", "''") + "', '" + desc.replace("'", "''") + "')" for word, desc in descriptions.items())
        # Literal AST values only; do not evaluate a command line to complete it.
        cases = '\n'.join("        '" + k + "' { $items = @(" + ','.join("'" + v + "'" for v in vs) + "); break }" for k, vs in {**values, 'get': list(FIELDS)}.items())
        return '''# Generated by wttr; no weather calls.
Register-ArgumentCompleter -Native -CommandName wttr,wttr.ps1 -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)
    $parts = @($commandAst.CommandElements | Where-Object { $_.Extent.EndOffset -le $cursorPosition } | ForEach-Object { $_.Extent.Text })
    $index = $parts.Count - 1
    if ($wordToComplete -and $index -ge 0 -and $parts[$index] -eq $wordToComplete) { $index-- }
    $prev = if ($index -ge 0) { $parts[$index] } else { '' }
    $items = @('OPTIONS','get','completion','browse','STOCK')
    if ($parts.Count -gt 1 -and $parts[1] -eq 'completion') { $items = @('bash','zsh','fish','powershell','--all','--install','--dir','HELP_FLAGS') }
    if ($parts.Count -gt 1 -and $parts[1] -eq 'browse') { $items = @('BROWSE_OPTIONS') }
    switch -CaseSensitive ($prev) {
CASES
    }
    if ($prev -cin @('FILE_FLAGS')) {
        [System.Management.Automation.CompletionCompleters]::CompleteFilename($wordToComplete)
        return
    }
    $descriptions = [System.Collections.Generic.Dictionary[string,string]]::new([StringComparer]::Ordinal)
TOOLTIPS
    $items | Where-Object { $_.StartsWith($wordToComplete, [StringComparison]::Ordinal) } | ForEach-Object {
        $tip = if ($descriptions.ContainsKey($_)) { $descriptions[$_] } else { $_ }
        [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $tip)
    }
}
'''.replace('BROWSE_OPTIONS', "','".join(browse_options.split())).replace('OPTIONS', "','".join(options.split())).replace('CASES', cases).replace('STOCK', "','".join(STOCK_WORDS)).replace('TOOLTIPS', tooltips).replace('FILE_FLAGS', "','".join(file_flags)).replace('HELP_FLAGS', "','".join(help_flags))
    raise ValueError('unknown completion shell')


def install(shells, directory=None):
    from file_platform import state_root
    from transactions import Store, digest, parents_safe
    operations, guards, targets = [], {}, []
    for shell in shells:
        parent = Path(directory).absolute() if directory else ROOT / 'shells' / shell / 'completions'
        path = parent / FILES[shell]
        parents_safe(path)
        if path.is_symlink() or (path.exists() and not path.is_file()):
            raise ValueError('completion target must be a regular file: ' + str(path))
        text = generate(shell)
        targets.append(path)
        before = digest(path)
        guards[str(path)] = before
        if path.exists() and path.read_text(encoding='utf-8') == text:
            continue
        operations.append({'path': str(path), 'text': text})
    result = Store(state_root()).apply('wttr-completion', operations, guards, retain=True)
    return result, targets
