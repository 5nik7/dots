"""Static Dots adapters derived from the standalone weather vocabulary."""
from metadata import OPTIONS, BROWSE_OPTIONS, COMPLETION_OPTIONS, FIELDS, SHELLS, STOCK_WORDS, SHORT_FLAGS

COMMANDS = {
    '': ('Show weather, query fields or browse forecasts', '[LOCATION|COMMAND|STOCK_OPTIONS] [OPTIONS]', OPTIONS),
    'get': ('Print one weather field', 'FIELD [OPTIONS]', OPTIONS),
    'browse': ('Browse weather with session location and unit controls', '[LOCATION] [OPTIONS]', BROWSE_OPTIONS),
    'completion': ('Generate or explicitly install weather completions', '[SHELL] [OPTIONS]',
                   [*COMPLETION_OPTIONS, *[row for row in OPTIONS if row[0] in ('--help', '--color', '--icons')]]),
}


def header(action):
    summary, usage, options = COMMANDS[action]
    rows = ['#!/usr/bin/env bash', '# Generated by tools/generate_wttr_commands.py.',
            '# dots:summary=' + summary, '# dots:usage=' + usage]
    for flag, value, description in options:
        kind = ('flag' if value is None else 'file' if flag == '--config' else
                'directory' if flag == '--dir' else 'choice:' + ','.join(FIELDS) if flag == '--get' else
                'choice:' + value.replace('|', ',') if '|' in value else 'string')
        rows.append('# dots:option=' + '|'.join((flag, SHORT_FLAGS.get(flag, ''), kind, description)))
    if action == 'get':
        rows.append('# dots:argument=1|choice:' + ','.join(FIELDS) + '|Weather field')
    elif action == 'completion':
        rows.append('# dots:argument=1|choice:' + ','.join(SHELLS) + '|Completion shell')
    elif action == '':
        rows.append('# dots:argument=*|choice:' + ','.join(STOCK_WORDS) + '|Location or stock weather option')
    else:
        rows.append('# dots:argument=1|string|Location override')
    rows += ['DOTS=${DOTS:-$(cd -- "${BASH_SOURCE[0]%/*}/.." && pwd -P)}',
             'exec python3 -B "$DOTS/lib/dots/wttr/cli.py" ' + (action + ' ' if action else '') + '"$@"']
    return '\n'.join(rows) + '\n'
