"""Static cleanup grammar and inert contextual completion."""
from cleanup.termux import GROUPS

COMMANDS = {
    '': ('Review known cleanup groups and reclaim storage', '[COMMAND] [OPTIONS]'),
    'scan': ('Inspect cleanup candidates without changing files or state', '[OPTIONS]'),
    'run': ('Delete reviewed cleanup groups with explicit approval', '[OPTIONS]'),
    'groups': ('List cleanup groups and platform support without scanning', '[OPTIONS]'),
    'history': ('List cleanup runs and cumulative verified totals', '[--limit N] [OPTIONS]'),
    'report': ('Show a cleanup receipt; defaults to the latest run', '[RUN_ID] [OPTIONS]'),
}
COMMON = [('--json','','flag','Print schema-1 JSON without decoration'),
          ('--quiet','-q','flag','Suppress routine human output'),
          ('--verbose','-v','flag','Show target paths and per-rule outcomes'),
          ('--color','','choice:auto,always,never','Human output colors'),
          ('--icons','','choice:auto,always,never','Human output icons')]
FILTERS = [('--group','','choice:'+','.join(GROUPS),'Select an exact group; repeatable'),
           ('--exclude','','choice:'+','.join(GROUPS),'Exclude a group; repeatable'),
           ('--include-checkpoints','','flag','Explicitly include all checkpoint risk groups'),
           ('--older-than','','string','Minimum checkpoint age in days'),
           ('--dry-run','','flag','Preview without prompting or writing state'),
           ('--progress','','choice:auto,never','Transient human progress')]
OPTIONS = {action: COMMON[:] for action in COMMANDS}
for action in ('', 'scan', 'run'): OPTIONS[action] += FILTERS
for action in ('', 'run'): OPTIONS[action] += [('--yes','-y','flag','Approve ordinary groups only; unattended use requires run')]
OPTIONS['history'] += [('--limit','','string','Maximum runs; 0 lists all (default 20)')]


def header(action):
    summary, usage = COMMANDS[action]
    lines = ['#!/usr/bin/env bash', '# Generated by tools/generate_cleanup_commands.py.',
             '# dots:summary='+summary, '# dots:usage='+usage]
    lines += ['# dots:option='+'|'.join(option) for option in OPTIONS[action]]
    if not action: lines.append('# dots:argument=1|choice:'+','.join(k for k in COMMANDS if k)+'|Command')
    if action == 'report': lines.append('# dots:argument=1|string|Full cleanup run UUID')
    lines += ['DOTS=${DOTS:-$(cd -- "${BASH_SOURCE[0]%/*}/.." && pwd -P)}',
              'exec python3 -B "$DOTS/lib/dots/cleanup_cli.py" '+(action+' ' if action else '')+'"$@"']
    return '\n'.join(lines)+'\n'


def complete(words):
    current = words[-1] if words else ''
    action = ''; pending = None; positional = []
    all_options = {o[0]: o for rows in OPTIONS.values() for o in rows}
    aliases = {o[1]: o[0] for o in all_options.values() if o[1]}
    for word in words[:-1]:
        if pending: pending = None
        elif word.startswith('-'):
            flag, equal, _ = word.partition('='); flag = aliases.get(flag, flag)
            if flag not in all_options: return
            if all_options[flag][2] != 'flag' and not equal: pending = flag
        elif not action and word in COMMANDS: action = word
        else: positional.append(word)
    lead = ''
    if current.startswith('--') and '=' in current:
        pending, _, current = current.partition('='); lead = pending+'='
    options = OPTIONS[action]
    choices = []
    if pending:
        option = next((o for o in options if o[0] == pending), None)
        if option and option[2].startswith('choice:'): choices = option[2][7:].split(',')
    elif current.startswith('-'):
        choices = [o[0] for o in options]+[o[1] for o in options if o[1]]+['--help']
    elif not action: choices = [a for a in COMMANDS if a]
    elif action == 'report' and not positional:
        from cleanup.receipts import Receipts
        try: choices = [r['id'] for r in Receipts().rows()]
        except (ValueError, OSError): return
    for choice in choices:
        if choice.startswith(current): print('candidate\t'+lead+choice+'\t')


if __name__ == '__main__':
    import sys
    complete(sys.argv[1:])
