"""Static backup grammar shared by help, completion and native adapters."""
COMMANDS = {
    '': ('Move files into recoverable backups or browse saved backups', '[COMMAND | PATH...] [OPTIONS]'),
    'create': ('Move files into backups; --copy retains originals', 'PATH... [OPTIONS]'),
    'list': ('List saved backups and protected uninstall baselines', '[OPTIONS]'),
    'show': ('Inspect a backup record without exposing file contents', 'ID [OPTIONS]'),
    'restore': ('Restore a backup and retain its saved version', 'ID [--to PATH] [OPTIONS]'),
    'delete': ('Delete selected unprotected backups and empty owned containers', 'ID... [OPTIONS]'),
    'prune': ('Review old backups selected by explicit retention filters', '[--keep COUNT] [--older-than DAYS] [OPTIONS]'),
    'import': ('Register existing legacy backups in place', 'PATH... [--original PATH] [OPTIONS]'),
    'browse': ('Browse, inspect and manage saved backups', '[OPTIONS]'),
}
COMMON = [('--json','','flag','Print schema-1 JSON without decoration'),
          ('--quiet','-q','flag','Suppress routine output; retain errors'),
          ('--verbose','-v','flag','Show transaction operation details'),
          ('--dry-run','','flag','Preview without changing files or state'),
          ('--yes','-y','flag','Approve explicit delete/prune or menu restoration'),
          ('--color','','choice:auto,always,never','Human output colors'),
          ('--icons','','choice:auto,always,never','Human output icons')]
STORAGE = [('--store','-s','flag','Use the configured backup store'),
           ('--store-dir','','directory','Override the backup store directory'),
           ('--in-place','','flag','Use adjacent filename.timestamp.bak backups')]
OPTIONS = {
    'create': STORAGE + [('--copy','','flag','Keep the original'), ('--move','','flag','Move the original (default)')],
    'restore': STORAGE + [('--to','','file','Restore to another pathname'), ('--no-backup','','flag','Discard the occupied destination after successful restore')],
    'prune': [('--keep','','string','Keep this many newest backups per original path'), ('--older-than','','string','Select backups older than this many days')],
    'import': [('--original','','file','Record the original path for one legacy backup')],
}


def header(action):
    summary, usage = COMMANDS[action]
    options = COMMON + (OPTIONS.get(action, []) if action else OPTIONS['create'])
    lines = ['#!/usr/bin/env bash', '# Generated by tools/generate_backup_commands.py.',
             '# dots:summary=' + summary, '# dots:usage=' + usage]
    lines += ['# dots:option=' + '|'.join(option) for option in options]
    if not action:
        lines += ['# dots:argument=1|choice:' + ','.join(k for k in COMMANDS if k) + '|Action or source path']
    elif action in ('create','import'):
        lines += ['# dots:argument=*|file|Source path']
    lines += ['DOTS=${DOTS:-$(cd -- "${BASH_SOURCE[0]%/*}/.." && pwd -P)}',
              'exec python3 -B "$DOTS/lib/dots/bak_cli.py" ' + (action + ' ' if action else '') + '"$@"']
    return '\n'.join(lines) + '\n'
